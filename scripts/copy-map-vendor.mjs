/**
 * Copy the map page's browser dependencies out of node_modules into
 * `public/map/vendor/`.
 *
 * The map page is plain HTML with no bundler behind it, so it loads MapLibre
 * and the PMTiles protocol shim with <script> tags. Those files still come from
 * npm — the versions are pinned in package.json and updated by `npm update`
 * like everything else — they just need to sit somewhere the page can link to.
 * Copying beats a CDN here because the whole point of the tile bundle is that
 * the map has no third-party runtime dependencies.
 *
 * `public/map/vendor/` is gitignored: it is build output, regenerated by the
 * predev/prebuild hooks in package.json.
 */

import { copyFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dest = join(root, "public", "map", "vendor");

const FILES = [
  "maplibre-gl/dist/maplibre-gl.js",
  "maplibre-gl/dist/maplibre-gl.css",
  "maplibre-gl/dist/LICENSE.txt",
  "pmtiles/dist/pmtiles.js",
];

await mkdir(dest, { recursive: true });
for (const file of FILES) {
  const name = file.split("/").pop();
  // MapLibre's license file would collide with any other package's, so it is
  // named for the package it covers.
  const out = name === "LICENSE.txt" ? "maplibre-gl-LICENSE.txt" : name;
  await copyFile(join(root, "node_modules", file), join(dest, out));
}

console.log(`Copied ${FILES.length} map vendor files into public/map/vendor`);
