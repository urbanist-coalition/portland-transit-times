/**
 * Bakes the e-ink display's glyph atlas from a real typeface.
 *
 * A panel is 1-bit: every pixel is ink or paper, with nothing in between. So
 * the type is thresholded exactly once, here, at known sizes — rather than at
 * render time, where it would be repeated work for an answer that never
 * changes. What ships is a table of glyph bitmaps; the renderer only blits.
 *
 * That is also why this is a build step and not a dependency. The worker draws
 * these frames beside everything else it writes each second, and a font
 * rasterizer in that loop would be a rasterizer in the path of every stop page
 * on the site.
 *
 *   npm run build:font-atlas
 *
 * Its output is committed, so a checkout needs neither this script nor the
 * fonts it reads. Re-run it only to change a size or a weight.
 */

import { writeFileSync } from "node:fs";
import { parse, raster } from "./lib/truetype.mjs";

const FONTS = "/usr/share/fonts/truetype/lato";

/**
 * The faces the layout asks for, by the name it asks for them by.
 *
 * Deliberately few. Every entry is ~6 KB of committed bitmaps, and a display
 * read from across a sidewalk has room for maybe three sizes that are actually
 * distinguishable — a fourth is decoration nobody standing at a stop can see.
 */
const FACES = {
  title: { file: "Lato-Bold.ttf", size: 34 },
  row: { file: "Lato-Semibold.ttf", size: 30 },
  time: { file: "Lato-Bold.ttf", size: 32 },
  badge: { file: "Lato-Black.ttf", size: 24 },
  small: { file: "Lato-Regular.ttf", size: 20 },
};

/** Printable ASCII, which is all but one character the feed has ever used. */
const FIRST = 0x20;
const LAST = 0x7e;

/**
 * The rest, and what to draw them with.
 *
 * U+21E8 is the arrow name disambiguation puts between a stop and where it is
 * headed ("Washington Ave + Stonecrest Dr ⇨ Congress & Maine Med"), and Lato
 * has no glyph for it. Lato's own U+2192 is drawn in its place rather than
 * borrowing DejaVu's, which would set one character of a stop name in a
 * different typeface at a visibly different weight. U+2026 is the ellipsis
 * truncate() appends.
 */
const EXTRA = new Map([
  [0x2026, 0x2026],
  [0x21e8, 0x2192],
]);

const CODEPOINTS = [
  ...Array.from({ length: LAST - FIRST + 1 }, (_, i) => FIRST + i),
  ...EXTRA.keys(),
];

/** A glyph's rows as packed bytes, MSB first — the same order the panel wants. */
function pack(bits, w) {
  const stride = Math.ceil(w / 8);
  const bytes = Buffer.alloc(stride * bits.length);
  bits.forEach((row, y) => {
    for (let x = 0; x < w; x++) {
      if (row[x] === "1") bytes[y * stride + (x >> 3)] |= 0x80 >> (x & 7);
    }
  });
  return bytes.toString("base64");
}

/** Drops the all-paper rows the bounding box leaves at the edges. */
function trim(g) {
  let top = 0;
  let bottom = g.bits.length;
  while (top < bottom && !g.bits[top].includes("1")) top++;
  while (bottom > top && !g.bits[bottom - 1].includes("1")) bottom--;
  return { rows: g.bits.slice(top, bottom), top: g.top - top };
}

const atlas = { generated: new Date().toISOString(), faces: {} };

for (const [name, { file, size }] of Object.entries(FACES)) {
  const font = parse(`${FONTS}/${file}`);
  const glyphs = {};
  let ascent = 0;
  let descent = 0;

  for (const code of CODEPOINTS) {
    const g = raster(font, EXTRA.get(code) ?? code, size);
    if (!g.advance && code !== 0x20) {
      throw new Error(`${file} has no glyph for U+${code.toString(16)}`);
    }
    const { rows, top } = trim(g);
    glyphs[code] = {
      a: g.advance,
      w: rows.length ? g.w : 0,
      h: rows.length,
      t: top,
      l: g.left,
      b: rows.length ? pack(rows, g.w) : "",
    };
    ascent = Math.max(ascent, top);
    descent = Math.min(descent, top - rows.length);
  }

  atlas.faces[name] = { source: file, size, ascent, descent, glyphs };
  console.log(
    `[atlas] ${name.padEnd(6)} ${file.padEnd(20)} ${size}px  ` +
      `ascent ${ascent} descent ${descent}`
  );
}

/*
 * Emitted as a module rather than as JSON so it is imported the same way
 * everywhere — the worker under tsx, the build under Eleventy, and jest — none
 * of which agree about how a JSON import is spelled.
 */
const out = "src/lib/display/atlas.ts";
const body = JSON.stringify(atlas);
writeFileSync(
  out,
  `/* Generated by scripts/build-font-atlas.mjs. Do not edit by hand. */\n` +
    `import type { Atlas } from "./font";\n\n` +
    `export const ATLAS: Atlas = ${body};\n`
);
console.log(`[atlas] ${out} (${(body.length / 1024).toFixed(0)} KB)`);
